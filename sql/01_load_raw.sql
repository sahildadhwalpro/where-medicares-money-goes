-- =============================================================
-- 01  Load the raw CMS file (PostgreSQL)
-- Medicare Geographic Variation Public Use File, 2014-2024
-- 36,994 rows x 246 columns.
--
-- Every column is loaded as TEXT on purpose:
--   * the file marks suppressed values with "*" and blank PQI values with "NA",
--     which would make a numeric import fail
--   * nothing is guessed at import time; types are set in step 03, in SQL
--
-- BEFORE RUNNING: put the CSV in a folder the database can read.
--   On a Mac, /Users/Shared/medicare/ works. (Postgres usually cannot read
--   Desktop, Documents or Downloads because of macOS privacy settings.)
--   Then edit the file path in section 3.
--   Alternative: create the table (sections 1-2), then in pgAdmin right-click
--   raw.gv_raw > Import/Export Data, choose the CSV, and tick "Header".
-- =============================================================


